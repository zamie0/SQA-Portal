async function findRobotExecutable() {
  const pathEntries = (process.env.PATH ?? "").split(path.delimiter).filter(Boolean);
  const names = process.platform === "win32" ? ["robot.exe", "robot.bat", "robot.cmd"] : ["robot"];

  for (const entry of pathEntries) {
    for (const name of names) {
      const candidate = path.join(entry, name);
      try {
        await access(candidate, constants.X_OK);
        return candidate;
      } catch {
        // Continue searching PATH.
      }
    }
  }

  return null;
}

function runRobot(executable: string, robotPath: string, outputDir: string) {
  return new Promise<{ code: number | null; stdout: string; stderr: string }>((resolve, reject) => {
    const args = ["--outputdir", outputDir, robotPath];
    const isWindowsScript = process.platform === "win32" && /\.(bat|cmd)$/i.test(executable);
    const child = spawn(executable, args, {
      shell: isWindowsScript,
      windowsHide: true,
    });
    let stdout = "";
    let stderr = "";

    child.stdout?.on("data", (chunk) => {
      stdout += String(chunk);
    });
    child.stderr?.on("data", (chunk) => {
      stderr += String(chunk);
    });
    child.on("error", reject);
    child.on("close", (code) => resolve({ code, stdout, stderr }));
  });
}

function parseRobotSummary(outputXml: string) {
  const statusMatches = [...outputXml.matchAll(/<status status="(PASS|FAIL)"[^>]*>/g)];
  const elapsedMatch = outputXml.match(/elapsed="([^"]+)"/);
  const messageMatches = [...outputXml.matchAll(/<msg[^>]*>([^<]+)<\/msg>/g)];
  const hasFailure = statusMatches.some((match) => match[1] === "FAIL");

  return {
    status: !hasFailure && statusMatches.length > 0 ? "passed" : "failed",
    elapsed: elapsedMatch?.[1] ?? null,
    message:
      messageMatches.at(-1)?.[1]?.replace(/&lt;/g, "<").replace(/&gt;/g, ">") ??
      "Robot Framework execution completed.",
  };
}

function setupResponse(message: string, scriptPath?: string) {
  return NextResponse.json(
    {
      status: "setup_required",
      message:
        "Robot Framework is not available to the app. Install it and make sure the robot command is on PATH.",
      detail: message,
      scriptPath,
    },
    { status: 503 },
  );
}

export async function POST(request: NextRequest) {
  const body = await request.json().catch(() => null);
  const payload = cleanPayload(body);

  if (typeof payload === "string") {
    return new Response(payload, { status: 400 });
  }

  const executable = await findRobotExecutable();
  if (!executable) {
    return setupResponse("robot command was not found on PATH");
  }

  const runId = randomUUID();
  const runDir = path.join(tmpdir(), "sqa-portal-robot", runId);
  const scriptPath = path.join(runDir, "sqa-test-studio.robot");
  const outputPath = path.join(runDir, "output.xml");

  await mkdir(runDir, { recursive: true });
  await writeFile(scriptPath, buildRobotFile(payload), "utf8");

  try {
    const result = await runRobot(executable, scriptPath, runDir);
    const outputXml = await readFile(outputPath, "utf8").catch(() => "");
    const summary = outputXml ? parseRobotSummary(outputXml) : null;

    if (result.code !== 0) {
      return NextResponse.json(
        {
          status: "failed",
          message: "Robot Framework test failed.",
          stdout: result.stdout.trim(),
          stderr: result.stderr.trim(),
          scriptPath,
          outputPath,
          summary,
        },
        { status: 500 },
      );
    }

    return NextResponse.json({
      status: "completed",
      runId,
      scriptPath,
      outputPath,
      summary,
    });
  } catch (error) {
    const message = error instanceof Error ? error.message : "Unable to start Robot Framework";
    return setupResponse(message, scriptPath);
  }
}
