export const runtime = "nodejs";

type RobotRequest = {
  website: string;
  instruction: string;
  loginUrl?: string;
  username?: string;
  password?: string;
  expectedText?: string;
};

function cleanPayload(body: unknown): RobotRequest | string {
  if (!body || typeof body !== "object") return "Invalid payload";
  const raw = body as Record<string, unknown>;
  const website = String(raw.website ?? "").trim();
  const instruction = String(raw.instruction ?? "").trim();
  const loginUrl = String(raw.loginUrl ?? "").trim();
  const username = String(raw.username ?? "").trim();
  const password = String(raw.password ?? "").trim();
  const expectedText = String(raw.expectedText ?? "").trim();

  if (!website) return "Website URL is required";

  let parsed: URL;
  try {
    parsed = new URL(website);
  } catch {
    return "Website must be a valid absolute URL";
  }

  if (parsed.protocol !== "http:" && parsed.protocol !== "https:") {
    return "Only http and https URLs are supported";
  }

  const payload: RobotRequest = {
    website,
    instruction:
      instruction ||
      "Check the website availability and basic response health using Robot Framework.",
  };

  if (loginUrl) {
    try {
      const parsedLoginUrl = new URL(loginUrl);
      if (parsedLoginUrl.protocol !== "http:" && parsedLoginUrl.protocol !== "https:") {
        return "Only http and https login URLs are supported";
      }
      payload.loginUrl = loginUrl;
    } catch {
      return "Login URL must be a valid absolute URL";
    }
  }

  if (username) payload.username = username;
  if (password) payload.password = password;
  if (expectedText) payload.expectedText = expectedText;

  return payload;
}

function robotValue(value: string) {
  return value.replace(/\\/g, "\\\\").replace(/\$/g, "\\$").replace(/\r?\n/g, " ").trim();
}

